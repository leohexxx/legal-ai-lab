def generate_all():
    """生成所有案例卡 YAML 文件"""
    CASES_DIR.mkdir(parents=True, exist_ok=True)

    for case in CASES:
        case_id = case["case_id"]
        filepath = CASES_DIR / f"{case_id}.yml"

        # 构建 YAML 内容（手动控制格式以确保可读性和一致性）
        lines = []
        lines.append(f"case_id: \"{case['case_id']}\"")
        lines.append(f"title: \"{case['title']}\"")
        lines.append(f"domain: \"{case['domain']}\"")
        lines.append(f"related_categories:")

        for cat in case["related_categories"]:
            lines.append(f"  - \"{cat}\"")

        lines.append(f"source: \"{case['source']}\"")
        lines.append(f"publish_date: \"{case['publish_date']}\"")
        lines.append(f"summary: \"{case['summary']}\"")
        lines.append(f"facts: ")

        for fact in case["facts"]:
            lines.append(f"  - \"{fact}\"")

        lines.append(f"dispute_focus: \"{case['dispute_focus']}\"")
        lines.append(f"judgment: \"{case['judgment']}\"")
        lines.append(f"key_rules_applied: ")

        for rule in case["key_rules_applied"]:
            lines.append(f"  - rule_id: \"{rule['rule_id']}\"")
            explanation = rule["explanation"].replace('"', "'")
            lines.append(f"    explanation: \"{explanation}\"")

        lines.append(f"legal_principles: ")

        for principle in case["legal_principles"]:
            principle = principle.replace('"', "'")
            lines.append(f"  - \"{principle}\"")

        lines.append(f"relevance_score: {case['relevance_score']}")

        content = "\n".join(lines)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)
            f.write("\n")

        print(f"  ✓ 已生成: {case_id}.yml")


