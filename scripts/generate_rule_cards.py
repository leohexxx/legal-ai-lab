# 验证
# ──────────────────────────────────────────────

def validate_all():
    """验证所有 YAML 文件可被 yaml.safe_load() 正确解析."""
    errors = []
    count = 0

    for rule in RULES:
        filepath = RULES_DIR / f"{rule['rule_id']}.yml"
        if not filepath.exists():
            errors.append(f"缺失文件: {filepath.name}")
            continue
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                data = yaml.safe_load(f)
            if data is None:
                errors.append(f"空文件: {filepath.name}")
            elif data.get("rule_id") != rule["rule_id"]:
                errors.append(f"rule_id 不符: {filepath.name}")
            else:
                count += 1
        except yaml.YAMLError as e:
            errors.append(f"YAML解析错误: {filepath.name}: {e}")

    if errors:
        print(f"\n❌ 验证发现 {len(errors)} 个错误:")
        for err in errors:
            print(f"  - {err}")
    else:
        print(f"\n✅ 全部 {count} 个文件验证通过（yaml.safe_load() 解析正常）")


